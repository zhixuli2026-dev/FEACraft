"""Archive the serial Code_Aster database using its native state files."""
import json
import shutil
from zipfile import ZIP_DEFLATED, ZipFile


SCHEMA = 'vibeflow.code-aster-base.v1'
HEADER = 'base.json'
MEMBERS = ('glob.1','pick.code_aster.infos','pick.code_aster.objects','pick.code_aster.sha')
LIMIT = 128*1024*1024


def validate(path, runtime, destination=None):
    if path.stat().st_size>LIMIT:
        raise ValueError('Code_Aster base archive exceeds 128 MiB')
    with ZipFile(path) as archive:
        members = archive.infolist()
        if (len(members)!=len(MEMBERS)+1 or {item.filename for item in members}!={HEADER,*MEMBERS}
                or any(item.compress_type!=ZIP_DEFLATED or item.file_size<=0 for item in members)
                or sum(item.file_size for item in members)>LIMIT or archive.getinfo(HEADER).file_size>512):
            raise ValueError('Code_Aster archive does not contain a bounded serial base')
        if json.loads(archive.read(HEADER))!={'schema':SCHEMA,'runtime_package_sha256':runtime}:
            raise ValueError('Code_Aster base was generated by a different solver build')
        if destination is not None:
            destination.mkdir(parents=True,exist_ok=False)
            for name in MEMBERS:
                with archive.open(name) as incoming, (destination/name).open('xb') as outgoing:
                    shutil.copyfileobj(incoming,outgoing,length=1024*1024)


def pack(files, destination, runtime):
    if set(files)!=set(MEMBERS) or sum(path.stat().st_size for path in files.values())>LIMIT-512:
        raise ValueError('Code_Aster base is incomplete or exceeds 128 MiB')
    with ZipFile(destination,'x',compression=ZIP_DEFLATED,compresslevel=3) as archive:
        archive.writestr(HEADER,json.dumps({'schema':SCHEMA,'runtime_package_sha256':runtime},sort_keys=True))
        for name in MEMBERS:
            archive.write(files[name],name)
    validate(destination,runtime)
